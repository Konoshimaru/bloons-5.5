// js/mapMeta.js
// Presentation metadata for the map select menu. Kept out of data.js (which is
// huge, machine-edited path data) so tiers can be tweaked in one obvious place.
//
// Tiers follow BTD6's logic: easier maps have a long, open path with plenty of
// room; harder ones are short, cramped, or have several paths to cover.
// Keyed by the map's `image` name (stable even if the display name changes).
// Custom (editor-made) maps always land in the "Custom" tab; any built-in map
// missing from this table defaults to Intermediate.

export const MAP_TIERS = Object.freeze([
    { id: 'beginner',     label: 'Beginner',     color: '#2ecc71' },
    { id: 'intermediate', label: 'Intermediate', color: '#3498db' },
    { id: 'advanced',     label: 'Advanced',     color: '#e74c3c' },
    { id: 'expert',       label: 'Expert',       color: '#9b59b6' },
    { id: 'custom',       label: 'Custom',       color: '#e67e22' },
]);

const TIER_BY_IMAGE = Object.freeze({
    // Beginner: single, fairly long path with open ground
    monkey_meadow: 'beginner',
    parkpath: 'beginner',
    candy_lane: 'beginner',
    enchanted_forest: 'beginner',
    // Intermediate: more obstacles / tighter turns
    AlpineRun: 'intermediate',
    winter_falls: 'intermediate',
    neon_alley: 'intermediate',
    spiral: 'intermediate',
    // Advanced: awkward layouts or short exposure
    maze: 'advanced',
    intersection: 'advanced',
    ripples: 'advanced',
    // Expert: several paths or a very short path
    bloon_circle: 'expert',
    volcanic_ridge: 'expert',
});

export function getMapTier(map, isCustom = false) {
    if (isCustom) return 'custom';
    return TIER_BY_IMAGE[map && map.image] || 'intermediate';
}

export function getTierInfo(id) {
    return MAP_TIERS.find(t => t.id === id) || MAP_TIERS[1];
}

// Small WebP preview generated by `npm run gen:thumbs`. The menu falls back to
// the full image if a thumbnail doesn't exist yet (e.g. a brand-new map).
export function getMapThumbUrl(map) {
    return map && map.image ? `sprites/maps/thumbs/${map.image}.webp` : '';
}
export function getMapFullUrl(map) {
    return map && map.image ? `sprites/maps/${map.image}.png` : '';
}
