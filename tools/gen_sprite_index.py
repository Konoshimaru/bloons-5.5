#!/usr/bin/env python3
"""Generate js/spriteIndex.js — a complete sprite catalog for the cutscene editor.

Sources:
  1. Loose PNG/JPG/WEBP/SVG files under public/sprites/** (minus maps/__pycache__ junk)
  2. Atlas frames from every sheet listed in public/sprites/manifest.json
     (frame names as used by Assets/sheetHasFrame, drawn by cropping the sheet png)

Output format (imported by js/cutsceneEditor.js):
  export const SPRITE_LIBRARY = [
    { key: 'boss_knight_back_1',  url: 'sprites/boss/knight_back_1.png', group: 'boss' },
    { key: 'bfb_1',               url: 'sprites/sheets/bfb/bfb.png',     group: 'sheet:bfb',
      sx: 12, sy: 0, sw: 64, sh: 64, fw: 64, fh: 64 },   # atlas frame crop
    ...
  ];
Loose files also get a derived Assets-style key (folder prefix -> key) so game
integration can resolve the same actor through Assets.get(key).
"""
import json, os, re

ROOT = '/home/z/my-project/btd_repo'
PUB = os.path.join(ROOT, 'public')
SPR = os.path.join(PUB, 'sprites')

# Assets-style folder map (from js/assets.js) for deriving game keys from paths.
FOLDER_MAP = {
    'boss_': 'boss', 'enemies_': 'enemies', 'bloons_': 'bloons', 'maps_': 'maps',
    'towers_': 'towers', 'projectiles_': 'projectiles', 'effects_': 'effects',
    'menu_': 'menu', 'portraits_': 'portraits',
}

IMG_EXT = ('.png', '.jpg', '.jpeg', '.webp', '.svg')

loose = []
for dirpath, dirnames, filenames in os.walk(SPR):
    dirnames[:] = [d for d in dirnames if d not in ('maps',)] or dirnames
    for fn in sorted(filenames):
        if not fn.lower().endswith(IMG_EXT):
            continue
        full = os.path.join(dirpath, fn)
        rel = os.path.relpath(full, PUB).replace(os.sep, '/')  # e.g. sprites/boss/ball_1.png
        # skip atlas sheets themselves (they're consumed via frames)
        m = re.match(r'sprites/sheets/([^/]+)/\1\.(png|jpg)$', rel)
        if m:
            continue
        group = os.path.dirname(rel)[len('sprites/'):] or 'sprites'
        entry = { 'key': None, 'url': rel, 'group': group }
        # derive Assets-style key: sprites/<folder>/<name>.ext  ->  <prefix><name>
        folder = os.path.dirname(rel)[len('sprites/'):]
        prefix = None
        for p, f in FOLDER_MAP.items():
            if f == folder:
                prefix = p
                break
        if prefix:
            base = os.path.splitext(fn)[0]
            entry['key'] = prefix + base
        loose.append(entry)

manifest = json.load(open(os.path.join(SPR, 'manifest.json')))
atlas = []
for sheet in manifest.get('sheets', []):
    sid = sheet['id']
    json_path = os.path.join(PUB, sheet['json'].lstrip('/'))
    png_path = sheet['png']
    if not os.path.exists(json_path):
        print(f'!! missing sheet json: {json_path}')
        continue
    try:
        data = json.load(open(json_path))
    except Exception as e:
        print(f'!! bad sheet json {sid}: {e}')
        continue
    frames = data.get('frames', {})
    for fname, fdef in sorted(frames.items()):
        fr = fdef.get('frame', {})
        entry = {
            'key': fname[:-4] if fname.endswith('.png') else fname,
            'url': png_path,
            'group': f'sheet:{sid}',
        }
        # trimmed frame rect on the sheet + original size for centered draws
        for k_out, k_in in (('sx', 'x'), ('sy', 'y'), ('sw', 'w'), ('sh', 'h')):
            entry[k_out] = fr.get(k_in)
        if fdef.get('trimmed') and 'spriteSourceSize' in fdef and 'sourceSize' in fdef:
            entry['ox'] = fdef['spriteSourceSize']['x']
            entry['oy'] = fdef['spriteSourceSize']['y']
            entry['fw'] = fdef['sourceSize']['w']
            entry['fh'] = fdef['sourceSize']['h']
        atlas.append(entry)

# Hand-maintained aliases: Assets keys referenced by game code that the
# folder-prefix scanner can't derive (file lives outside FOLDER_MAP folders).
# fw/fh = design size (px) so the editor draws the sprite at the same visual
# size as the in-game fit box (knight front/back poses share one fit box;
# knight_front.png is 69x66 native but must preview like the 122x115 backs).
ALIASES = [
    { 'key': 'enemy_knight_front', 'url': 'sprites/sheets/enemies/knight_front.png',
      'group': 'boss', 'fw': 122, 'fh': 117 },
]

lines = []
lines.append('// js/spriteIndex.js — GENERATED by scripts/gen_sprite_index.py. Do not edit by hand.')
lines.append('// Complete sprite catalog for the cutscene editor sprite picker:')
lines.append('// every loose image under public/sprites/** plus every atlas frame')
lines.append('// from the sheets in public/sprites/manifest.json.')
lines.append('')
lines.append('export const SPRITE_LIBRARY = [')
for e in loose + atlas + ALIASES:
    parts = [f"key: {json.dumps(e['key'])}" if e.get('key') else 'key: null',
             f"url: {json.dumps(e['url'])}",
             f"group: {json.dumps(e['group'])}"]
    for k in ('sx', 'sy', 'sw', 'sh', 'ox', 'oy', 'fw', 'fh'):
        if e.get(k) is not None:
            parts.append(f"{k}: {e[k]}")
    lines.append('    { ' + ', '.join(parts) + ' },')
lines.append('];')
lines.append('')
lines.append('// Exact-key map (Assets-style keys), then url map, then null.')
lines.append('const BY_KEY = new Map();')
lines.append('const BY_URL = new Map();')
lines.append('for (const e of SPRITE_LIBRARY) {')
lines.append('    if (e.key && !BY_KEY.has(e.key)) BY_KEY.set(e.key, e);')
lines.append('    if (e.sx == null && !BY_URL.has(e.url)) BY_URL.set(e.url, e);')
lines.append('}')
lines.append('')
lines.append('/** Resolve a sprite reference (Assets key, atlas frame key, or url) to a')
lines.append(' *  library entry; returns null when unknown. */')
lines.append('export function findEntry(ref) {')
lines.append('    if (!ref) return null;')
lines.append('    return BY_KEY.get(ref) || BY_URL.get(ref) || null;')
lines.append('}')

out = os.path.join(ROOT, 'js', 'spriteIndex.js')
open(out, 'w').write('\n'.join(lines))
print(f'wrote {out}: {len(loose)} loose + {len(atlas)} atlas frames = {len(loose)+len(atlas)} entries')
